/**
 * Generates the shape morphs of the /3.0/ pages (m3.material.io/styles/
 * shape/shape-morph): for each pair in site/eleventy-helpers/gb-shapes.cjs
 * (MORPHS), the start and end paths of the Compose `Morph` between the two
 * Material shapes (scripts/m3/shapes, the port the loading indicator uses).
 * `Morph` matches the two shapes' cubics one to one, so CSS interpolates the
 * SVG `d: path()` between them; site/src/gb/morph.css animates them.
 *
 *   node scripts/gb-shape-morphs.mjs
 *
 * Writes site/src/gb/shape-morphs.css: per pair, `--gb-morph-from` and
 * `--gb-morph-to` on `.gb-shape[data-morph="<from>:<to>"]`, in the shapes'
 * 0..1 box (the viewBox of the inline SVGs).
 */

import {writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {Morph} from './m3/shapes/graphics-shapes.mjs';
import {MaterialShapes} from './m3/shapes/material-shapes.mjs';

const require = createRequire(import.meta.url);
const {MORPHS, morphKey} = require('../site/eleventy-helpers/gb-shapes.cjs');

const OUT = 'site/src/gb/shape-morphs.css';

/** The Compose name of a site shape name (cookie9Sided -> Cookie9Sided). */
function polygon(name) {
  const shape = MaterialShapes[name[0].toUpperCase() + name.slice(1)];
  if (!shape) throw new Error(`gb-shape-morphs: no MaterialShapes.${name}`);
  return shape;
}

/** Cubics (in the normalized 0..1 box) -> an SVG path (3 decimals: under
    half a pixel at the largest shape, 26rem). */
function svgPath(cubics) {
  const n = (v) => String(Math.round(v * 1e3) / 1e3).replace(/^(-?)0\./, '$1.');
  const p0 = cubics[0].points;
  const parts = [`M${n(p0[0])} ${n(p0[1])}`];
  for (const c of cubics) {
    const p = c.points;
    parts.push(`C${n(p[2])} ${n(p[3])} ${n(p[4])} ${n(p[5])} ${n(p[6])} ${n(p[7])}`);
  }
  return parts.join('') + 'Z';
}

const rules = MORPHS.map(([from, to]) => {
  const morph = new Morph(polygon(from), polygon(to));
  const start = svgPath(morph.asCubics(0));
  const end = svgPath(morph.asCubics(1));
  return `  .gb-shape[data-morph='${morphKey(from, to)}'] {\n    --gb-morph-from: path('${start}');\n    --gb-morph-to: path('${end}');\n  }`;
});

await writeFile(
  OUT,
  `/**
 * @license
 * Copyright 2026 Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

/* AUTOGENERATED by scripts/gb-shape-morphs.mjs from the Compose Morph of the
   Material shapes (scripts/m3/shapes, Apache-2.0): the start and end paths
   of each morph in site/eleventy-helpers/gb-shapes.cjs (MORPHS), with
   matched cubics. Animated by morph.css. Do not edit. */

@supports (d: path('M0 0')) {
${rules.join('\n')}
}
`,
);
console.log(`gb-shape-morphs: ${MORPHS.length} morphs -> ${OUT}`);
