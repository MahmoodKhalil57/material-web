/**
 * Generates the shape morphs (m3.material.io/styles/shape/shape-morph): for
 * each pair in site/eleventy-helpers/gb-shapes.cjs (MORPHS), the start and
 * end paths of the Compose `Morph` between the two Material shapes
 * (scripts/m3/shapes, the port the loading indicator uses). `Morph` matches
 * the two shapes' cubics one to one, so CSS interpolates the SVG
 * `d: path()` between them.
 *
 *   node scripts/gb-shape-morphs.mjs           # write
 *   node scripts/gb-shape-morphs.mjs --check   # fail if a file is stale
 *
 * Writes, in the shapes' 0..1 box:
 * - material-design-expressive/extras/shape/shape-morphs.ts: the paths of
 *   md-gb-shape's morphs (`to`), by "<from>:<to>";
 * - site/src/gb/shape-morphs.css: per pair, `--gb-morph-from` and
 *   `--gb-morph-to` on `.gb-shape[data-morph="<from>:<to>"]`, which
 *   site/src/gb/morph.css animates (the old shell's inline SVGs).
 */

import {readFile, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {Morph} from './m3/shapes/graphics-shapes.mjs';
import {MaterialShapes} from './m3/shapes/material-shapes.mjs';

const require = createRequire(import.meta.url);
const {MORPHS, morphKey} = require('../site/eleventy-helpers/gb-shapes.cjs');

const CSS_OUT = 'site/src/gb/shape-morphs.css';
const TS_OUT = 'material-design-expressive/extras/shape/shape-morphs.ts';
const CHECK = process.argv.includes('--check');

/** The Compose name of a site shape name (cookie9Sided -> Cookie9Sided). */
function polygon(name) {
  const shape = MaterialShapes[name[0].toUpperCase() + name.slice(1)];
  if (!shape) throw new Error(`gb-shape-morphs: no MaterialShapes.${name}`);
  return shape;
}

/** Cubics (in the normalized 0..1 box) -> an SVG path (3 decimals: under
    half a pixel at the largest shape, 26rem). */
function svgPath(cubics) {
  const n = (v) => String(Math.round(v * 1e3) / 1e3).replace(/^(-?)0\./, '$1.');
  const p0 = cubics[0].points;
  const parts = [`M${n(p0[0])} ${n(p0[1])}`];
  for (const c of cubics) {
    const p = c.points;
    parts.push(`C${n(p[2])} ${n(p[3])} ${n(p[4])} ${n(p[5])} ${n(p[6])} ${n(p[7])}`);
  }
  return parts.join('') + 'Z';
}

const morphs = MORPHS.map(([from, to]) => {
  const morph = new Morph(polygon(from), polygon(to));
  return {key: morphKey(from, to), start: svgPath(morph.asCubics(0)), end: svgPath(morph.asCubics(1))};
});

const LICENSE = `/**
 * @license
 * Copyright 2026 Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */
`;

const css = `${LICENSE}
/* AUTOGENERATED by scripts/gb-shape-morphs.mjs from the Compose Morph of the
   Material shapes (scripts/m3/shapes, Apache-2.0): the start and end paths
   of each morph in site/eleventy-helpers/gb-shapes.cjs (MORPHS), with
   matched cubics. Animated by morph.css. Do not edit. */

@supports (d: path('M0 0')) {
${morphs
  .map(
    ({key, start, end}) =>
      `  .gb-shape[data-morph='${key}'] {\n    --gb-morph-from: path('${start}');\n    --gb-morph-to: path('${end}');\n  }`,
  )
  .join('\n')}
}
`;

const ts = `${LICENSE}
// AUTOGENERATED. DO NOT MODIFY. Run node scripts/gb-shape-morphs.mjs
//
// The Compose Morph (androidx.graphics.shapes, Apache-2.0) between pairs of
// Material shapes: the start and end paths of each morph, with matched
// cubics, so CSS interpolates \`d: path()\` between them. In the shapes' 0..1
// box. md-gb-shape imports this module only when it morphs.

/** Morph paths by \`"<from>:<to>"\`: [start (the from shape), end (the to shape)]. */
export const SHAPE_MORPHS: Readonly<Record<string, readonly [string, string]>> = {
${morphs.map(({key, start, end}) => `  '${key}': [\n    '${start}',\n    '${end}',\n  ],`).join('\n')}
};
`;

let stale = 0;
for (const [file, content] of [
  [CSS_OUT, css],
  [TS_OUT, ts],
]) {
  if (CHECK) {
    const old = await readFile(file, 'utf8').catch(() => '');
    if (old.replace(/\r\n/g, '\n') !== content) {
      console.error(`gb-shape-morphs: ${file} is stale (run node scripts/gb-shape-morphs.mjs)`);
      stale++;
    }
  } else {
    await writeFile(file, content);
  }
}
if (stale) process.exit(1);
console.log(`gb-shape-morphs: ${MORPHS.length} morphs -> ${CHECK ? 'up to date' : `${CSS_OUT}, ${TS_OUT}`}`);
