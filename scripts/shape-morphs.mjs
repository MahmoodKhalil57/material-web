/**
 * Generates the shape morphs (m3.material.io/styles/shape/shape-morph): for
 * each pair of MORPHS (below), the start and
 * end paths of the Compose `Morph` between the two Material shapes
 * (scripts/m3/shapes, the port the loading indicator uses). `Morph` matches
 * the two shapes' cubics one to one, so CSS interpolates the SVG
 * `d: path()` between them.
 *
 *   node scripts/shape-morphs.mjs           # write
 *   node scripts/shape-morphs.mjs --check   # fail if a file is stale
 *
 * Writes material-design-expressive/extras/shape/shape-morphs.ts: the paths
 * of md-gb-shape's morphs (`to`), by "<from>:<to>", in the shapes' 0..1 box.
 */

import {readFile, writeFile} from 'node:fs/promises';
import {Morph} from './m3/shapes/graphics-shapes.mjs';
import {MaterialShapes} from './m3/shapes/material-shapes.mjs';

/**
 * The pairs md-gb-shape can morph between (`shape` -> `to`, and back), in
 * the order of shape-morphs.ts. Add a pair to morph another two shapes.
 */
const MORPHS = [
  ['cookie9Sided', 'flower'],
  ['clover4Leaf', 'clover8Leaf'],
  ['sunny', 'softBurst'],
  ['pill', 'oval'],
  ['clover4Leaf', 'sunny'],
  ['sunny', 'flower'],
  ['flower', 'puffy'],
  ['puffy', 'cookie6Sided'],
  ['cookie6Sided', 'softBurst'],
  ['softBurst', 'pill'],
  ['pill', 'pentagon'],
  ['pentagon', 'cookie12Sided'],
  ['cookie12Sided', 'gem'],
  ['gem', 'burst'],
  ['burst', 'cookie9Sided'],
  ['cookie9Sided', 'clover4Leaf'],
  ['cookie12Sided', 'cookie9Sided'],
  ['clover4Leaf', 'puffy'],
  ['sunny', 'verySunny'],
  ['softBurst', 'burst'],
  ['clover8Leaf', 'clover4Leaf'],
  ['burst', 'softBurst'],
  ['flower', 'cookie9Sided'],
  ['puffy', 'puffyDiamond'],
  ['gem', 'pentagon'],
  ['cookie6Sided', 'cookie9Sided'],
  ['puffyDiamond', 'puffy'],
  ['cookie4Sided', 'cookie6Sided'],
  ['softBoom', 'boom'],
];
const morphKey = (from, to) => `${from}:${to}`;

const TS_OUT = 'material-design-expressive/extras/shape/shape-morphs.ts';
const CHECK = process.argv.includes('--check');

/** The Compose name of a site shape name (cookie9Sided -> Cookie9Sided). */
function polygon(name) {
  const shape = MaterialShapes[name[0].toUpperCase() + name.slice(1)];
  if (!shape) throw new Error(`shape-morphs: no MaterialShapes.${name}`);
  return shape;
}

/** Cubics (in the normalized 0..1 box) -> an SVG path (3 decimals: under
    half a pixel at the largest shape, 26rem). */
function svgPath(cubics) {
  const n = (v) => String(Math.round(v * 1e3) / 1e3).replace(/^(-?)0\./, '$1.');
  const p0 = cubics[0].points;
  const parts = [`M${n(p0[0])} ${n(p0[1])}`];
  for (const c of cubics) {
    const p = c.points;
    parts.push(`C${n(p[2])} ${n(p[3])} ${n(p[4])} ${n(p[5])} ${n(p[6])} ${n(p[7])}`);
  }
  return parts.join('') + 'Z';
}

const morphs = MORPHS.map(([from, to]) => {
  const morph = new Morph(polygon(from), polygon(to));
  return {key: morphKey(from, to), start: svgPath(morph.asCubics(0)), end: svgPath(morph.asCubics(1))};
});

const LICENSE = `/**
 * @license
 * Copyright 2026 Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */
`;

const ts = `${LICENSE}
// AUTOGENERATED. DO NOT MODIFY. Run node scripts/shape-morphs.mjs
//
// The Compose Morph (androidx.graphics.shapes, Apache-2.0) between pairs of
// Material shapes: the start and end paths of each morph, with matched
// cubics, so CSS interpolates \`d: path()\` between them. In the shapes' 0..1
// box. md-gb-shape imports this module only when it morphs.

/** Morph paths by \`"<from>:<to>"\`: [start (the from shape), end (the to shape)]. */
export const SHAPE_MORPHS: Readonly<Record<string, readonly [string, string]>> = {
${morphs.map(({key, start, end}) => `  '${key}': [\n    '${start}',\n    '${end}',\n  ],`).join('\n')}
};
`;

if (CHECK) {
  const old = await readFile(TS_OUT, 'utf8').catch(() => '');
  if (old.replace(/\r\n/g, '\n') !== ts) {
    console.error(`shape-morphs: ${TS_OUT} is stale (run node scripts/shape-morphs.mjs)`);
    process.exit(1);
  }
} else {
  await writeFile(TS_OUT, ts);
}
console.log(`shape-morphs: ${MORPHS.length} morphs -> ${CHECK ? 'up to date' : TS_OUT}`);
