/** labs/gb components that have a demo. */
async function gbDemoDirs() {
  const dirs = [];
  for (const dir of (await readdir(GB)).sort()) {
    if (existsSync(join(GB, dir, 'demo', 'demo.ts'))) dirs.push(dir);
  }
  return dirs;
}

/**
 * Transpiles each component's demo (demo.ts + stories.ts) into
 * catalog/_dev-gb/<dir>/ with a stand-in for the catalog story framework that
 * renders each story into the docs page (or, in capture mode, records its
 * HTML). Served by the library server so bare imports resolve.
 */
async function prepareExamples(dirs) {
  const esbuild = await import('esbuild');
  await rm(EXAMPLES, {recursive: true, force: true});
  const tsconfigRaw = {compilerOptions: {experimentalDecorators: true, useDefineForClassFields: false}};
  for (const dir of dirs) {
    const demo = join(GB, dir, 'demo');
    for (const f of await readdir(demo)) {
      if (!f.endsWith('.ts')) continue;
      const source = (await readFile(join(demo, f), 'utf8')).replace(
        /(['"])([^'"]+)\.css\1\s+with\s*\{\s*type:\s*['"]css['"]\s*\}/g,
        '$1$2.cssresult.js$1',
      );
      const {code} = await esbuild.transform(source, {loader: 'ts', format: 'esm', target: 'esnext', tsconfigRaw});
      await mkdir(join(EXAMPLES, dir), {recursive: true});
      await writeFile(
        join(EXAMPLES, dir, f.replace(/\.ts$/, '.js')),
        code
          .replace(/(['"])@material\/web\//g, '$1/')
          .replace(/(['"])\.\/(material-collection|index)\.js\1/g, '$1../_shim.js$1'),
      );
    }
  }
  await writeFile(join(EXAMPLES, '_shim.js'), SHIM);
  await writeFile(
    join(EXAMPLES, 'capture.html'),
    `<!doctype html><html data-gb-capture><head><meta charset="utf-8"></head><body>
<script type="module">
const dir = new URLSearchParams(location.search).get('dir');
import('./' + dir + '/demo.js').catch((e) => { window.__gbError = String(e); });
</script></body></html>\n`,
  );
}

/** Renders every story in headless Chromium and returns its HTML. */
async function captureExamples(dirs) {
  let chromium;
  try {
    ({chromium} = await import('playwright'));
  } catch {
    console.warn('playwright is not installed; M3 Expressive pages get no code samples.');
    return new Map();
  }
  const browser = await chromium.launch();
  const examples = new Map();
  for (const dir of dirs) {
    // A fresh page per component: one page for all of them runs out of
    // resources (net::ERR_INSUFFICIENT_RESOURCES).
    const page = await browser.newPage();
    try {
      await page.goto(`${LIB}catalog/_dev-gb/capture.html?dir=${dir}`);
      await page.waitForFunction(() => window.__gbCapture || window.__gbError, null, {timeout: 20000});
      const {stories, error} = await page.evaluate(() => ({stories: window.__gbCapture, error: window.__gbError}));
      if (error) throw new Error(error);
      examples.set(dir, stories.map((s) => ({name: s.name, html: formatHtml(s.html)})));
    } catch (err) {
      console.warn(`  ${dir}: could not capture examples (${err.message.split('\n')[0]})`);
    } finally {
      await page.close();
    }
  }
  await browser.close();
  console.log(`Captured examples for ${examples.size}/${dirs.length} components`);
  return examples;
}

/**
 * Adds a stories folder and a docs page for every labs/gb component that has
 * a demo. Both land in gitignored catalog folders.
 */
async function addExpressiveComponents(dirs, examples) {
  const added = [];
  for (const dir of dirs) {
    const demo = join(GB, dir, 'demo');
    const dirname = `gb-${dir}`;
    const stories = join(CATALOG, 'stories', dirname);
    await rm(stories, {recursive: true, force: true});
    await cp(demo, stories, {recursive: true});
    await writeFile(
      join(stories, 'project.json'),
      JSON.stringify(
        {extends: '/assets/stories/base.json', files: {'demo.ts': {hidden: true}, 'stories.ts': {}}},
        null,
        2,
      ) + '\n',
    );
    const doc = await describeComponent(dir);
    await writeFile(
      join(CATALOG, 'site', 'components', `${dirname}.md`),
      docsPage(dir, dirname, doc, examples.get(dir) ?? []),
    );
    added.push(doc.title);
  }
  console.log(`${added.length} M3 Expressive components: ${added.join(', ')}`);
  return added;
}

/** Reads the title from the demo and the API from the element's jsdoc. */
async function describeComponent(dir) {
  const files = await readdir(join(GB, dir));
  const demo = await readFile(join(GB, dir, 'demo', 'demo.ts'), 'utf8');
  const title = demo.match(/MaterialCollection<[^>]*>>\(\s*'([^']+)'/)?.[1] ?? dir;

  // Tag names from md-gb-*.ts registrations.
  const tags = new Map(); // class -> tag
  for (const f of files.filter((f) => /^md-gb-.*\.ts$/.test(f) && !f.endsWith('.d.ts'))) {
    const src = await readFile(join(GB, dir, f), 'utf8');
    for (const m of src.matchAll(/customElements\.define\(\s*'([^']+)'\s*,\s*(\w+)\s*\)/g)) tags.set(m[2], m[1]);
  }

  const elements = [];
  for (const f of files.filter((f) => /-element\.ts$/.test(f) && !f.endsWith('.d.ts'))) {
    const src = (await readFile(join(GB, dir, f), 'utf8')).replace(/\r\n/g, '\n');
    const cls = src.match(/\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*export class (\w+)/);
    if (!cls) continue;
    const doc = jsdoc(cls[1]);
    const properties = [];
    for (const m of src.matchAll(
      /\/\*\*((?:(?!\*\/)[\s\S])*)\*\/\s*@property\(([^)]*)\)\s*(?:override\s+)?(?:accessor\s+)?(\w+)\??\s*(?::\s*([^=;]+?))?\s*(?:=\s*([^;]+))?;/g,
    )) {
      const [, comment, options, name, type, value] = m;
      const attribute = options.match(/attribute:\s*'([^']+)'/)?.[1] ?? name.toLowerCase();
      properties.push({
        name,
        attribute: /attribute:\s*false/.test(options) ? '' : attribute,
        type: (type ?? options.match(/type:\s*(\w+)/)?.[1] ?? '').trim(),
        default: (value ?? '').trim(),
        description: jsdoc(comment).text,
      });
    }
    elements.push({tag: tags.get(cls[2]) ?? '', className: cls[2], ...doc, properties});
  }
  return {title, elements};
}

function jsdoc(block) {
  const lines = block.split('\n').map((l) => l.replace(/^\s*\* ?/, '').trimEnd());
  const text = [];
  const tags = {cssprop: [], fires: [], slot: [], csspart: []};
  for (const line of lines) {
    const m = line.match(/^@(cssprop|fires|slot|csspart)\s+(.*)$/);
    if (m) tags[m[1]].push(m[2]);
    else if (!line.startsWith('@') && !Object.values(tags).some((t) => t.length)) text.push(line);
  }
  return {text: text.join(' ').replace(/\s+/g, ' ').trim(), ...tags};
}

function docsPage(dir, dirname, {title, elements}, stories) {
  const main = elements.find((e) => e.tag) ?? elements[0];
  const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/[{}]/g, (c) => `&#${c.charCodeAt(0)};`);
  const usage = elements
    .filter((e) => e.tag)
    .map((e) => `import '@material/web/labs/gb/components/${dir}/${e.tag}.js';`)
    .join('\n');
  const api = elements
    .filter((e) => e.tag)
    .map((e) => {
      const out = [`### &lt;${e.tag}&gt;`, '', e.text, ''];
      if (e.properties.length) {
        out.push('#### Properties', '', '| Property | Attribute | Type | Default | Description |', '| --- | --- | --- | --- | --- |');
        for (const p of e.properties) {
          out.push(`| \`${p.name}\` | ${p.attribute ? `\`${p.attribute}\`` : ''} | \`${esc(p.type)}\` | ${p.default ? `\`${esc(p.default)}\`` : ''} | ${esc(p.description)} |`);
        }
        out.push('');
      }
      const list = (heading, items) => {
        if (!items.length) return;
        out.push(`#### ${heading}`, '', ...items.map((i) => `*   ${esc(i.replace(/^(\S+)/, '`$1`'))}`), '');
      };
      list('Slots', e.slot);
      list('Events', e.fires);
      list('CSS parts', e.csspart);
      list('CSS custom properties', e.cssprop);
      return out.join('\n');
    })
    .join('\n');

  return `---
name: ${title}
dirname: ${dirname}
expressive: true
tags: [expressive]
ssrOnly: true
---

<catalog-component-header>
<catalog-component-header-title slot="title">

# ${title}

${esc(main?.text ?? '')}

This is an M3 Expressive component from \`labs/gb\`, built locally from this
repository.

</catalog-component-header-title>

${
  stories.length
    ? `<div class="gb-hero" data-gb-story="${heroStory(stories)}" role="img" aria-label="${title} examples"></div>`
    : ''
}

</catalog-component-header>

## Interactive Demo

{% playgroundexample dirname=dirname %}

${examplesSections(stories)}

## Usage

\`\`\`js
${usage}
\`\`\`

Every component also has a class API for plain HTML; see
\`labs/gb/components/${dir}/\` and its stories above.

## API

${api}

<style>
  .gb-hero {
    align-items: center;
    background: var(--md-sys-color-surface-container-lowest);
    border-radius: var(--catalog-image-border-radius);
    box-sizing: border-box;
    display: flex;
    justify-content: center;
    min-height: 240px;
    overflow: hidden;
    padding: 24px;
    zoom: 1.25;
  }
  figure:has(> .gb-example) {
    max-width: 100%;
    overflow-x: auto;
  }
  .gb-example {
    max-width: 100%;
  }
</style>
<script type="module" src="${LIB}catalog/_dev-gb/${dir}/demo.js"></script>
`;
}

/** Knob-driven "Playground" stories belong to the interactive demo. */
function isPlayground(story) {
  return /^playground$/i.test(story.name);
}

/** Header example: the first story that shows the component's range. */
function heroStory(stories) {
  const index = stories.findIndex((s) => !isPlayground(s));
  return index >= 0 ? index : 0;
}

/**
 * One section per story (except the Playground, which is the interactive
 * demo): a live figure, like the other component pages, and its HTML.
 */
function examplesSections(stories) {
  const sections = stories
    .map((story, index) => ({story, index}))
    .filter(({story}) => !isPlayground(story) || stories.length === 1);
  return sections
    .map(({story, index}) => {
      return `## ${story.name}

<div class="figure-wrapper">
  <figure aria-label="${story.name} example"><div class="gb-example" data-gb-story="${index}"></div></figure>
</div>

{% raw %}
\`\`\`html
${story.html}
\`\`\`
{% endraw %}
`;
    })
    .join('\n');
}

/** Minimal HTML pretty-printer for captured story markup. */
function formatHtml(html) {
  const VOID = /^(area|base|br|col|embed|hr|img|input|link|meta|source|track|wbr)$/i;
  const tokens = html
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s(class|style)=""/g, '')
    .match(/<[^>]+>|[^<]+/g) ?? [];
  const lines = [];
  let depth = 0;
  for (let i = 0; i < tokens.length; i++) {
    const t = tokens[i];
    const pad = '  '.repeat(depth);
    if (/^<\//.test(t)) {
      depth = Math.max(0, depth - 1);
      lines.push('  '.repeat(depth) + t);
    } else if (/^</.test(t)) {
      const tag = t.match(/^<([\w-]+)/)?.[1] ?? '';
      const text = tokens[i + 1];
      const close = tokens[i + 2];
      // <tag>text</tag> on one line.
      if (text && !/^</.test(text) && close === `</${tag}>`) {
        lines.push(pad + t + text.trim().replace(/\s+/g, ' ') + close);
        i += 2;
      } else if (tokens[i + 1] === `</${tag}>`) {
        lines.push(pad + t + tokens[i + 1]);
        i += 1;
      } else {
        lines.push(pad + t);
        if (!VOID.test(tag) && !t.endsWith('/>')) depth++;
      }
    } else if (t.trim()) {
      lines.push(pad + t.trim().replace(/\s+/g, ' '));
    }
  }
  return lines.join('\n');
}

/** Points the playground sandbox and import map at the local library. */
async function useLocalLibrary() {
  const sandbox = `${LIB}node_modules/playground-elements/`;
  const importMap = {
    imports: {
      '@material/web/': LIB,
      'lit': `${LIB}node_modules/lit/index.js`,
      'lit/': `${LIB}node_modules/lit/`,
      '@lit/context': `${LIB}node_modules/@lit/context/index.js`,
      'postdoc-lib': `${LIB}node_modules/postdoc-lib/lib/postdoc.js`,
    },
  };
  let pages = 0;
  let projects = 0;
  for (const file of await walk(OUT)) {
    if (file.endsWith('.html')) {
      const html = await readFile(file, 'utf8');
      if (!html.includes('<playground-project')) continue;
      await writeFile(file, html.replace(/<playground-project(?![^>]*sandbox-base-url)/g, `<playground-project sandbox-base-url="${sandbox}"`));
      pages++;
    } else if (file.endsWith('project.json')) {
      const project = JSON.parse(await readFile(file, 'utf8'));
      project.importMap = importMap;
      await writeFile(file, JSON.stringify(project, null, 2));
      projects++;
    }
  }
  console.log(`${pages} pages and ${projects} playground projects use ${LIB}`);
}

async function walk(dir, out = []) {
  for (const entry of await readdir(dir, {withFileTypes: true})) {
    const p = join(dir, entry.name);
    if (entry.isDirectory()) await walk(p, out);
    else out.push(p);
  }
  return out;
}

/** The library: this repo, with bare imports resolved (playground + examples). */
async function startLibraryServer() {
  const {startDevServer} = await import('@web/dev-server');
  await startDevServer({
    config: {
      rootDir: ROOT,
      port: LIB_PORT,
      nodeResolve: true,
      middleware: [
        (ctx, next) => {
          ctx.set('Access-Control-Allow-Origin', '*');
          return next();
        },
      ],
    },
    readCliArgs: false,
    readFileConfig: false,
    logStartMessage: false,
  });
}

/** The catalog site. */
async function startCatalogServer() {
  const {startDevServer} = await import('@web/dev-server');
  await startDevServer({
    config: {rootDir: OUT, port: PORT, open: argv.includes('--no-open') ? false : '/'},
    readCliArgs: false,
    readFileConfig: false,
    logStartMessage: false,
  });
}
