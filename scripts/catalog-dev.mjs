/**
 * Runs the material-web.dev catalog locally against the local build, with the
 * M3 Expressive `labs/gb` components added under an "M3 Expressive" section.
 * Works on Windows, macOS and Linux.
 *
 *   npm run catalog:dev                    # build everything, serve, open
 *   npm run catalog:dev -- --skip-build    # reuse the last library build
 *   npm run catalog:dev -- --port 8000 --lib-port 8001 --no-open
 *
 * On material-web.dev, stories run in a playground that loads the published
 * @material/web from unpkg. Here the playground sandbox and an import map
 * point at a second local server that serves this repo, so every story (old
 * and new components) runs the code in your working tree.
 */

import {existsSync} from 'node:fs';
import {cp, mkdir, readdir, readFile, rm, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {buildLibrary, nodeScript, npx, ROOT} from './build-local.mjs';

const CATALOG = join(ROOT, 'catalog');
const GB = join(ROOT, 'labs', 'gb', 'components');
const OUT = join(CATALOG, '_dev');
const EXAMPLES = join(CATALOG, '_dev-gb');

/**
 * Stand-in for the catalog story framework (./material-collection.js and
 * ./index.js) used by labs/gb demos. Renders each story with its default knob
 * values into `[data-gb-story="<index>"]` on the docs page, inside a shadow
 * root so story CSS stays scoped; in capture mode records the story HTML.
 */
const SHIM = `// Generated by scripts/catalog-dev.mjs.
import {render} from 'lit';

export class Knob {
  constructor(name, options = {}) {
    this.name = name;
    this.defaultValue = options.defaultValue;
  }
}
const ui = () => ({});
export const boolInput = ui;
export const numberInput = ui;
export const selectDropdown = ui;
export const textInput = ui;
export const colorPicker = ui;
export const title = ui;

export class MaterialCollection {
  constructor(title, knobs = []) {
    this.title = title;
    this.knobs = knobs;
    this.stories = [];
  }
  addStories(...stories) {
    this.stories.push(...stories);
  }
}
export function materialInitsToStoryInits(inits) {
  return inits;
}

const base = new CSSStyleSheet();
base.replaceSync(\`
  :host { color: var(--md-sys-color-on-surface); }
  .gb-story { box-sizing: border-box; max-width: 100%; padding-block: 16px; }
\`);

export async function setUpDemo(collection) {
  const knobs = Object.fromEntries(collection.knobs.map((k) => [k.name, k.defaultValue]));
  const capture = document.documentElement.hasAttribute('data-gb-capture');
  const results = [];
  for (const [i, story] of collection.stories.entries()) {
    const hosts = capture
      ? [document.body.appendChild(document.createElement('div'))]
      : [...document.querySelectorAll('[data-gb-story="' + i + '"]')];
    for (const host of hosts) {
      const root = host.shadowRoot ?? host.attachShadow({mode: 'open'});
      const styles = [story.styles].flat().filter(Boolean).map((s) => s.styleSheet ?? s);
      root.adoptedStyleSheets = [base, ...styles];
      const container = document.createElement('div');
      container.className = 'gb-story';
      root.replaceChildren(container);
      render(await story.render({...knobs}), container);
      if (capture) results.push({name: story.name, html: container.innerHTML});
    }
  }
  if (capture) window.__gbCapture = results;
}
`;

const argv = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = argv.indexOf(`--${name}`);
  return i >= 0 ? argv[i + 1] : fallback;
};
const PORT = Number(arg('port', 8000));
const LIB_PORT = Number(arg('lib-port', 8001));
const LIB = `http://localhost:${LIB_PORT}/`;
const log = (s) => console.log(`\n[catalog:dev] ${s}`);
const DEV_ENV = {NODE_ENV: 'DEV'};

if (!argv.includes('--skip-build')) await buildLibrary({log});

log('Copying docs and stories');
nodeScript(['scripts/copy-docs.mjs'], {cwd: CATALOG});
nodeScript(['scripts/copy-stories.mjs'], {cwd: CATALOG});

log('Preparing live examples for M3 Expressive pages');
const gbDirs = await gbDemoDirs();
await prepareExamples(gbDirs);
await startLibraryServer();
const examples = await captureExamples(gbDirs);
const expressive = await addExpressiveComponents(gbDirs, examples);

log('Bundling catalog scripts');
nodeScript(['esbuild.config.mjs'], {cwd: CATALOG, env: DEV_ENV});

log('Building pages (Eleventy)');
await rm(OUT, {recursive: true, force: true});
npx(['eleventy'], {cwd: CATALOG, env: DEV_ENV});

log('Pointing playgrounds at the local build');
await useLocalLibrary();

await startCatalogServer();
log(
  `Catalog: http://localhost:${PORT}/  (${expressive.length} M3 Expressive components)\n` +
    `[catalog:dev] Library: ${LIB} (serves this repo for the playground)\n` +
    `[catalog:dev] After editing sources, rerun (add --skip-build if only docs or demos changed).`,
);

