/**
 * Gives every example on the existing pages of VARIANTS an M3 Expressive
 * variant: each figure, each `html` code block and the interactive demo is
 * duplicated, the copy rewritten to labs/gb elements, and the header toggle
 * shows one or the other. Markup is rewritten in a browser (DOM APIs).
 */
async function addExpressiveVariants() {
  const {chromium} = await import('playwright');
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const modules = await gbElementModules();
  let count = 0;
  for (const [slug, dir] of Object.entries(VARIANTS)) {
    const file = join(CATALOG, 'site', 'components', `${slug}.md`);
    if (!existsSync(file)) continue;
    const lines = (await readFile(file, 'utf8')).split('\n');
    const blocks = findExampleBlocks(lines);
    const transformed = await page.evaluate(
      ({src, items}) => {
        const transform = eval(`(${src})`);
        return items.map((html) => transform(html));
      },
      {src: transformToExpressive.toString(), items: blocks.map((b) => b.html)},
    );
    // Rebuild from the end so earlier line numbers stay valid.
    const tags = new Set();
    for (let i = blocks.length - 1; i >= 0; i--) {
      const block = blocks[i];
      const expressive = transformed[i];
      if (!expressive) continue;
      for (const m of expressive.matchAll(/<(md-gb-[a-z-]+)/g)) tags.add(m[1]);
      const original = lines.slice(block.start, block.end + 1).join('\n');
      let clean = expressive.replace(/ ([\w-]+)=""/g, ' $1').replace(/[ \t]+$/gm, '');
      // A blank line ends a markdown HTML block, which would cut a figure
      // in half; figures keep none.
      if (block.kind === 'figure') clean = clean.replace(/\n{2,}/g, '\n');
      else clean = clean.replace(/\n{3,}/g, '\n\n');
      const replacement =
        block.kind === 'figure'
          ? `<div data-variant="standard">\n${original}\n</div>\n<div data-variant="expressive">\n${clean}\n</div>`
          : `<div data-variant="standard">\n\n${original}\n\n</div>\n<div data-variant="expressive">\n\n\`\`\`html\n${clean}\n\`\`\`\n\n</div>`;
      lines.splice(block.start, block.end - block.start + 1, replacement);
    }
    let md = lines.join('\n');
    md = md.replace(
      /^\{% playgroundexample dirname=dirname %\}$/m,
      `<div data-variant="standard">\n\n{% playgroundexample dirname=dirname %}\n\n</div>\n` +
        `<div data-variant="expressive">\n\n{% playgroundexample dirname="gb-${dir}", id="project-gb" %}\n\n</div>`,
    );
    md = withExpressiveApi(md, dir);
    md = md.replace(/^---\n/, `---\nexpressiveDir: ${dir}\n`);
    md += `\n<script type="module">if (location.pathname.startsWith('/3.0/')) import('${LIB}catalog/_dev-gb/variants/${slug}.js');</script>\n`;
    await writeFile(file, md);

    // Loads the labs/gb elements used by the Expressive variants.
    const imports = [...tags].map((t) => modules.get(t)).filter(Boolean);
    await mkdir(join(EXAMPLES, 'variants'), {recursive: true});
    await writeFile(
      join(EXAMPLES, 'variants', `${slug}.js`),
      `// Generated by scripts/catalog-dev.mjs.\n` +
        `import {adoptStyles} from '/labs/gb/styles/adopt-styles.js';\n` +
        `import {styles as m3Styles} from '/labs/gb/styles/m3.cssresult.js';\n` +
        [...new Set(imports)].map((p) => `import '${p}';`).join('\n') +
        `\nadoptStyles(document, [m3Styles]);\n`,
    );
    count++;
  }
  await browser.close();
  console.log(`${count} pages with Expressive variants`);
  return count;
}

/**
 * Keeps the v2.5.0 "API" section for "/" and shows the md-gb-* tables, read
 * from the labs/gb sources (scripts/m3/gen-api-docs.mjs), in /3.0/.
 */
function withExpressiveApi(md, dir) {
  const api = gbApiMarkdown(dir);
  if (!api) return md;
  const start = md.search(/^## API[ \t]*$/m);
  const tail = start < 0 ? -1 : md.slice(start + 6).search(/^(?:## |<style|<script)/m);
  const end = tail < 0 ? md.length : start + 6 + tail;
  const original = start < 0 ? '' : md.slice(start, end).trim();
  const head = start < 0 ? md.trimEnd() + '\n\n' : md.slice(0, start);
  return (
    head +
    (original ? `<div data-variant="standard">

${original}

</div>
` : '') +
    `<div data-variant="expressive">

## API

${api}
</div>

` +
    md.slice(end)
  );
}

/**
 * The About and Theming pages describe v2.5.0. scripts/catalog-3.0/<section>/
 * <page>.md hold the M3 Expressive text for the sections whose facts differ:
 * each heading in such a file replaces the section with the same heading (the
 * last match; a `# ` heading keeps its title and replaces the body to the end
 * of the page), and the original is kept for "/" as a standard variant.
 */
async function addExpressivePageSections() {
  const root = join(ROOT, 'scripts', 'catalog-3.0');
  const headings = (ls) => {
    const found = [];
    let fence = false;
    ls.forEach((l, i) => {
      if (/^(```|~~~)/.test(l)) fence = !fence;
      const m = !fence && /^(#{1,6}) (.+?)\s*$/.exec(l);
      if (m) found.push({i, level: m[1].length, text: m[2], line: l});
    });
    return found;
  };
  let count = 0;
  for (const section of await readdir(root)) {
    for (const f of await readdir(join(root, section))) {
      const target = join(CATALOG, 'site', section, f);
      if (!f.endsWith('.md')) continue;
      // A file with `expressiveOnly: true` front matter is a new page that only
      // exists in /3.0/ (a new section folder gets the docs layout and a
      // collection named after it). It is copied on every run: the copy from
      // the last run is still in catalog/site, and must not be treated as a
      // page whose sections get replaced.
      const text = await readFile(join(root, section, f), 'utf8');
      const front = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] ?? '';
      const newPage = /^expressiveOnly: true\s*$/m.test(front);
      if (!newPage && !existsSync(target)) {
        throw new Error(`catalog-3.0/${section}/${f}: no page to update; mark new pages expressiveOnly: true`);
      }
      if (newPage) {
        const dir = join(CATALOG, 'site', section);
        if (!existsSync(dir)) await mkdir(dir, {recursive: true});
        const json = join(dir, `${section}.json`);
        if (!existsSync(json)) {
          await writeFile(json, JSON.stringify({layout: 'layouts/docs.html', tags: [section], hasToc: true}, null, 2));
        }
        await writeFile(target, text);
        count++;
        continue;
      }
      const lines = (await readFile(target, 'utf8')).split('\n');
      const source = (await readFile(join(root, section, f), 'utf8')).split('\n');
      // Split the replacement file into sections at its first heading's level.
      const sh = headings(source);
      const level = sh[0].level;
      const chunks = sh
        .filter((h) => h.level === level)
        .map((h, n, all) => {
          const end = all[n + 1] ? all[n + 1].i : source.length;
          const from = level === 1 ? h.i + 1 : h.i;
          return {...h, body: source.slice(from, end).join('\n').trim()};
        });
      for (const chunk of chunks) {
        const th = headings(lines);
        const matches = th.filter((h) => h.level === level && h.text === chunk.text);
        if (!matches.length) throw new Error(`catalog-3.0/${section}/${f}: no "${chunk.line}"`);
        const at = matches[matches.length - 1];
        const next = th.find((h) => h.i > at.i && h.level <= level);
        const start = level === 1 ? at.i + 1 : at.i;
        const end = level === 1 || !next ? lines.length : next.i;
        const original = lines.slice(start, end).join('\n').trim();
        lines.splice(
          start,
          end - start,
          `<div data-variant="standard">\n\n${original}\n\n</div>\n` +
            `<div data-variant="expressive">\n\n${chunk.body}\n\n</div>\n`,
        );
      }
      await writeFile(target, lines.join('\n'));
      count++;
    }
  }
  console.log(`${count} docs pages with Expressive sections or 3.0-only pages`);
  return count;
}

/** Figures (`<div class="figure-wrapper">`) and top-level ```html blocks. */
function findExampleBlocks(lines) {
  const blocks = [];
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*<div class="figure-wrapper">/.test(lines[i])) {
      let depth = 0;
      let j = i;
      for (; j < lines.length; j++) {
        depth += (lines[j].match(/<div\b/g) ?? []).length;
        depth -= (lines[j].match(/<\/div>/g) ?? []).length;
        if (depth <= 0) break;
      }
      blocks.push({kind: 'figure', start: i, end: j, html: lines.slice(i, j + 1).join('\n')});
      i = j;
    } else if (/^```html\s*$/.test(lines[i])) {
      let j = i + 1;
      while (j < lines.length && !/^```\s*$/.test(lines[j])) j++;
      blocks.push({kind: 'code', start: i, end: j, html: lines.slice(i + 1, j).join('\n')});
      i = j;
    }
  }
  return blocks;
}

