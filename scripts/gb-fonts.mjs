/**
 * Self-hosts the /3.0/ site's fonts: Roboto Flex (OFL) and Material Symbols
 * Outlined (Apache 2.0). Downloads the Google Fonts CSS and its woff2 files
 * once, saves the files under content-hash names in catalog/site/fonts/gb/
 * (served at /fonts/gb/ with an immutable, one-year Cache-Control in
 * firebase.json, and cache-first in the service worker), and writes
 * catalog/site/fonts/gb/fonts.css with the @font-face rules and
 * catalog/site/_data/gbFonts.json with the files to preload.
 *
 *   node scripts/gb-fonts.mjs        # re-run to update the fonts; commit the output
 *
 * Roboto Flex is `swap` (text shows at once in the size-matched fallback,
 * gb.css), Material Symbols `block` (icon names never show as text). Both
 * are preloaded, so after the first visit they are ready before first paint.
 */

import {createHash} from 'node:crypto';
import {mkdir, readdir, rm, writeFile} from 'node:fs/promises';
import {join} from 'node:path';

const OUT = join('catalog', 'site', 'fonts', 'gb');
const DATA = join('catalog', 'site', '_data', 'gbFonts.json');
// A current Chrome user agent, so Google Fonts answers with woff2.
const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0.0.0 Safari/537.36';
const FAMILIES = [
  {
    css: 'https://fonts.googleapis.com/css2?family=Roboto+Flex:opsz,wght@8..144,100..1000&display=swap',
    // The Latin subset is the one every page needs.
    preload: (rule) => /\/\* latin \*\//.test(rule),
  },
  {
    // All four axes: components set FILL and opsz, and the Material Symbols
    // page demos weight and grade too.
    css: 'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@20..48,100..700,0..1,-50..200&display=block',
    preload: () => true,
  },
];

async function get(url, as) {
  const res = await fetch(url, {headers: {'User-Agent': UA}});
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return as === 'text' ? res.text() : Buffer.from(await res.arrayBuffer());
}

await rm(OUT, {recursive: true, force: true});
await mkdir(OUT, {recursive: true});
const css = [
  '/* Generated by scripts/gb-fonts.mjs from Google Fonts. Roboto Flex: SIL Open',
  '   Font License 1.1. Material Symbols: Apache License 2.0. */',
  '',
];
const preload = [];
let total = 0;
for (const source_ of FAMILIES) {
  const source = await get(source_.css, 'text');
  // Each @font-face block, with the comment (subset name) before it.
  const blocks = source.match(/(?:\/\*[^*]*\*\/\s*)?@font-face\s*\{[^}]*\}/g) ?? [];
  for (const block of blocks) {
    const url = /url\((https:[^)]+\.woff2)\)/.exec(block)?.[1];
    if (!url) continue;
    const bytes = await get(url);
    const family = /font-family:\s*'([^']+)'/.exec(block)[1].replace(/\s+/g, '-').toLowerCase();
    const name = `${family}-${createHash('sha256').update(bytes).digest('hex').slice(0, 12)}.woff2`;
    await writeFile(join(OUT, name), bytes);
    total += bytes.length;
    css.push(block.replace(url, `./${name}`).trim(), '');
    if (source_.preload(block)) preload.push(`/fonts/gb/${name}`);
  }
}
// The Material Symbols class Google's CSS includes is not needed (md-gb-icon
// styles itself); keep only the @font-face rules.
const fontsCss = css.join('\n').replace(/\.material-symbols-outlined\s*\{[^}]*\}\s*/g, '');
await writeFile(join(OUT, 'fonts.css'), fontsCss);
await writeFile(DATA, JSON.stringify({stylesheet: '/fonts/gb/fonts.css', preload}, null, 2) + '\n');
const files = (await readdir(OUT)).filter((f) => f.endsWith('.woff2'));
console.log(`gb-fonts: ${files.length} files, ${(total / 1024).toFixed(0)} KB; preload ${preload.length}`);
