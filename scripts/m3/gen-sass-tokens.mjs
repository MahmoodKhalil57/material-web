/**
 * Generates `tokens/versions/latest/sass/` (every md.ref, md.sys and md.comp
 * token set) from the M3 docs export downloaded by
 * `scripts/download-m3-specs.mjs`, in the same format as the upstream token
 * compiler.
 *
 *   node scripts/m3/gen-sass-tokens.mjs [--out <dir>] [--specs .m3-specs]
 *
 * Default output is `.m3-specs/out/sass`; pass
 * `--out tokens/versions/latest/sass` to update the repo.
 */

import {mkdir, readdir, writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {SpecDb, WEB_CONTEXT} from './spec-db.mjs';

const args = Object.fromEntries(
  process.argv.slice(2).map((a, i, all) => {
    const [k, v] = a.replace(/^--/, '').split('=');
    return [k, v ?? all[i + 1]];
  }),
);
const OUT = args.out ?? '.m3-specs/out/sass';
const db = await SpecDb.load(args.specs ?? '.m3-specs');

/** Context variants that get their own `__suffix` module when they differ. */
const VARIANTS = [
  ['__dark', {theme: 'dark'}],
  ['__medium-contrast', {contrast: 'medium.contrast'}],
  ['__high-contrast', {contrast: 'high.contrast'}],
  ['__dark__medium-contrast', {theme: 'dark', contrast: 'medium.contrast'}],
  ['__dark__high-contrast', {theme: 'dark', contrast: 'high.contrast'}],
  // M3 Expressive motion (springs) as published under `motion.scheme`.
  ['__expressive', {'motion.scheme': 'expressive'}],
];

export const moduleName = (set) => set.replace(/\./g, '-');
const varName = (tokenName, set) => tokenName.slice(set.length + 1).replace(/\./g, '-');

const modules = [];
const skipped = [];
for (const set of [...db.sets.keys()].sort()) {
  if (!/^md\./.test(set)) {
    skipped.push(set);
    continue;
  }
  // Variable-font typescales only apply to the `font: variable` context.
  if (WEB_CONTEXT.font === 'static' && /\.variable(\.|$)/.test(set)) {
    skipped.push(set);
    continue;
  }
  const base = renderSet(set, WEB_CONTEXT);
  if (!base) {
    skipped.push(set);
    continue;
  }
  const name = moduleName(set);
  await emit(name, base);
  for (const [suffix, overrides] of VARIANTS) {
    const variant = renderSet(set, {...WEB_CONTEXT, ...overrides});
    if (variant && variant.body !== base.body) await emit(name + suffix, variant);
  }
}
// Forward every module in the folder, including sets the docs no longer
// publish (those files are left untouched rather than deleted).
const allModules = (await readdir(OUT))
  .filter((f) => /^_.+\.scss$/.test(f) && f !== '_index.scss' && !f.endsWith('-meta.scss'))
  .map((f) => f.slice(1, -'.scss'.length));
const kept = allModules.filter((m) => !modules.includes(m));
await writeFile(
  join(OUT, '_index.scss'),
  header('index.scss.tmpl') +
    allModules
      .sort()
      .map((m) => `@forward '${m}' as ${m}--*;\n`)
      .join(''),
);
console.log(`Wrote ${modules.length} modules to ${OUT}/ (spec ${db.version}).`);
if (kept.length) console.log(`Kept modules not in the docs: ${kept.join(', ')}`);
if (skipped.length) console.log(`Skipped sets: ${skipped.join(', ')}`);

async function emit(name, {uses, body}) {
  modules.push(name);
  await mkdir(OUT, {recursive: true});
  const useLines = [...uses].sort().map((u) => `@use '${u}';\n`).join('');
  await writeFile(
    join(OUT, `_${name}.scss`),
    header('contextualtokenset.scss.tmpl') + (useLines ? useLines + '\n' : '') + body,
  );
}

function header(template) {
  return `//
// Copyright 2026 Google LLC
// SPDX-License-Identifier: Apache-2.0
//
// AUTOGENERATED. DO NOT MODIFY.
// To modify this file, run: node scripts/m3/gen-sass-tokens.mjs
// Source template: formats/sassvars/${template}

// Design system: Google Material 3
// Version: m3.material.io ${db.version}
// Configured context tags:
${Object.entries(WEB_CONTEXT)
  .filter(([k]) => k !== 'theme')
  .sort()
  .map(([k, v]) => `//   ${k}: ${v}\n`)
  .join('')}// Output format: sass_vars

`;
}

/** Renders one token set, or undefined if no token resolves in `ctx`. */
function renderSet(set, ctx) {
  const uses = new Set();
  const literals = [];
  const refs = [];
  const mixins = [];
  for (const tokenName of [...db.sets.get(set)].sort()) {
    const r = db.resolve(tokenName, ctx);
    if (!r) continue;
    const doc = docComment(tokenName);
    const name = varName(tokenName, set);
    const type = db.type(tokenName);

    // A token that aliases a whole typescale (even if typed e.g. FONT_SIZE)
    // is emitted as a mixin, like typography tokens.
    if (type === 'TYPOGRAPHY' || (r.ref && db.type(r.ref) === 'TYPOGRAPHY')) {
      const lines = typographyMixin(r, set, uses);
      if (lines) mixins.push(`${doc}@mixin ${name} {\n${lines}}\n`);
      continue;
    }
    if (r.ref) {
      const refSet = db.tokens.get(r.ref)?.set;
      if (refSet && refSet !== set && /^md\./.test(refSet)) {
        uses.add(moduleName(refSet));
        refs.push(`${doc}$${name}: ${moduleName(refSet)}.$${varName(r.ref, refSet)};\n`);
        continue;
      }
      if (refSet === set) {
        refs.push(`${doc}$${name}: $${varName(r.ref, set)};\n`);
        continue;
      }
      // References to unpublished sets (e.g. goog.ref.*) are inlined.
      const value = literal(r.resolved ?? r.value, type);
      if (value !== undefined) refs.push(`${doc}$${name}: ${value};\n`);
      continue;
    }
    const value = literal(r.value ?? r.resolved, type);
    if (value !== undefined) literals.push(`${doc}$${name}: ${value};\n`);
  }
  const body = [...literals, ...refs, ...mixins].join('');
  return body ? {uses, body} : undefined;
}

function docComment(tokenName) {
  const {token} = db.tokens.get(tokenName);
  const path = db.displayPath(tokenName);
  let doc = `/// ${tokenName}${path ? ` (${path})` : ''}\n`;
  if (token.description) {
    doc += '///\n' + token.description.split('\n').map((l) => `/// ${l}`.trimEnd() + '\n').join('');
  }
  if (token.deprecationMessage) {
    doc += `///\n/// @deprecated ${token.deprecationMessage.message}\n`;
  }
  return doc;
}

/** `@include md-sys-typescale.label-large` or font property declarations. */
function typographyMixin(r, set, uses) {
  if (r.ref && !r.value?.type) {
    const refSet = db.tokens.get(r.ref)?.set;
    if (!refSet) return undefined;
    if (refSet !== set) uses.add(moduleName(refSet));
    const prefix = refSet === set ? '' : `${moduleName(refSet)}.`;
    return `  @include ${prefix}${varName(r.ref, refSet)};\n`;
  }
  const t = r.value?.type ?? r.resolved?.type;
  if (!t) return undefined;
  const props = [
    ['font-family', t.fontNameTokenName],
    ['font-size', t.fontSizeTokenName],
    ['font-weight', t.fontWeightTokenName],
    ['letter-spacing', t.fontTrackingTokenName],
    ['line-height', t.lineHeightTokenName],
  ];
  let out = '';
  for (const [prop, ref] of props) {
    if (!ref) continue;
    const refSet = db.tokens.get(ref)?.set ?? set;
    if (refSet !== set) uses.add(moduleName(refSet));
    out += `  ${prop}: ${refSet === set ? '' : moduleName(refSet) + '.'}$${varName(ref, refSet)};\n`;
  }
  return out;
}

/** Formats a literal value record like the upstream sass_vars compiler. */
export function literal(v, type) {
  if (!v) return undefined;
  if (v.undefined) return undefined;
  if (v.color) return hex(v.color);
  if (v.length) return dimension(v.length);
  if (v.elevation) return dimension(v.elevation);
  if (v.opacity !== undefined) return num(v.opacity);
  if (v.numeric !== undefined) return num(v.numeric);
  if (v.durationMs !== undefined) return `${num(v.durationMs)}ms`;
  if (v.cubicBezier) {
    const {x0 = 0, y0 = 0, x1 = 0, y1 = 0} = v.cubicBezier;
    return `cubic-bezier(${[x0, y0, x1, y1].map(num).join(', ')})`;
  }
  if (v.shape) return shape(v.shape);
  if (v.axisValue) return `'${v.axisValue.tag}' ${num(v.axisValue.value ?? 0)}`;
  if (v.fontWeight !== undefined) return num(v.fontWeight);
  if (v.fontNames) return v.fontNames.values.map(fontName).join(', ');
  if (v.fontSize) return dimension(v.fontSize);
  if (v.fontTracking) return dimension(v.fontTracking);
  if (v.lineHeight) return dimension(v.lineHeight);
  if (v.textTransform) return v.textTransform.replace(/^TEXT_TRANSFORM_/, '').toLowerCase();
  const kind = (type ?? 'unknown').toLowerCase();
  return `/* Type "${kind}" is not supported. */ null`;
}

function fontName(name) {
  return /^[\w-]+$/.test(name) ? name : `'${name}'`;
}

function dimension({value = 0, unit}) {
  switch (unit) {
    case 'POINTS':
      return value === 0 ? '0rem' : `${num(value / 16)}rem`;
    case 'PERCENT':
      return `${num(value)}%`;
    default:
      return `${num(value)}px`;
  }
}

function shape({family, defaultSize, topLeft, topRight, bottomRight, bottomLeft}) {
  if (family === 'SHAPE_FAMILY_CIRCULAR') return '9999px';
  const corners = [topLeft, topRight, bottomRight, bottomLeft];
  if (corners.some(Boolean)) {
    // Unset corners without a default size are written as a unitless 0.
    return corners.map((c) => ((c ?? defaultSize) ? dimension(c ?? defaultSize) : '0')).join(' ');
  }
  return dimension(defaultSize ?? {});
}

function hex({red = 0, green = 0, blue = 0, alpha = 1}) {
  const parts = [red, green, blue].map((c) => Math.round(c * 255));
  if (alpha !== 1) return `rgba(${parts.join(', ')}, ${num(alpha)})`;
  let h = parts.map((c) => c.toString(16).padStart(2, '0')).join('');
  if (/^(.)\1(.)\2(.)\3$/.test(h)) h = h[0] + h[2] + h[4];
  return `#${h}`;
}

function num(n) {
  return String(Math.round(n * 1e6) / 1e6);
}
