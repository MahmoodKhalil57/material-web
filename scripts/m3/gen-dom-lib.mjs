/** TypeScript helpers of the measurement tests. */
export const MEASURE_HELPERS = String.raw`/** 1dp is 1px. Values may be off by up to half a pixel. */
const TOLERANCE = 0.5;

type Spec = {eq?: number; min?: number; max?: number; full?: boolean; like?: string; rel?: string};

/** The box of an element, or of its pseudo-element, in px. */
function boxOf(el: HTMLElement, pseudo: string) {
  if (!pseudo) {
    const {width, height} = el.getBoundingClientRect();
    return {width, height};
  }
  const style = getComputedStyle(el, pseudo);
  return {width: parseFloat(style.width), height: parseFloat(style.height)};
}

/** Resolves a length in px (a percentage is of the second argument). */
function px(value: string, of: number) {
  return value.endsWith('%') ? (parseFloat(value) / 100) * of : parseFloat(value);
}

/**
 * The visible size of a part cut out of its box with clip-path inset(),
 * e.g. a switch handle.
 */
function clipSize(el: HTMLElement, pseudo: string) {
  const box = boxOf(el, pseudo);
  const clip = getComputedStyle(el, pseudo).clipPath;
  const half = /inset\(calc\(50% - ([\d.]+)px\)/.exec(clip);
  if (half) return parseFloat(half[1]) * 2;
  const inset = /inset\(([\d.]+)px/.exec(clip);
  if (inset) return box.height - 2 * parseFloat(inset[1]);
  throw new Error('no inset() clip-path on ' + (pseudo || 'element') + ': ' + clip);
}

/** Measures a part of the mounted component, in px (dp). */
/** The box a part is measured against: another part, or the window. */
function relRect(rel: string) {
  if (rel === 'window') return new DOMRect(0, 0, window.innerWidth, window.innerHeight);
  return need(rel).getBoundingClientRect();
}

function measure(chain: string, metric: string, pseudo = '', rel = ''): number {
  if (chain === 'window') return metric === 'width' ? window.innerWidth : window.innerHeight;
  const el = need(chain);
  const box = boxOf(el, pseudo);
  if (metric === 'width' || metric === 'height') return box[metric];
  const style = getComputedStyle(el, pseudo);
  // A custom property: prop:--name, in px.
  if (metric.startsWith('prop:')) return parseFloat(style.getPropertyValue(metric.slice('prop:'.length)));
  switch (metric) {
    case 'offset-left':
    case 'offset-right':
    case 'offset-top':
    case 'offset-bottom': {
      // The distance from the part's edge to the same edge of rel.
      const a = el.getBoundingClientRect();
      const b = relRect(rel);
      const edge = metric.slice('offset-'.length);
      return edge === 'left' ? a.left - b.left : edge === 'right' ? b.right - a.right : edge === 'top' ? a.top - b.top : b.bottom - a.bottom;
    }
    case 'clip-offset-left': {
      // Where a part cut out with clip-path: inset() starts, from the left edge of rel.
      const m = /inset\(([^)]*?)(?: round [^)]*)?\)/.exec(style.clipPath);
      if (!m) throw new Error('no inset() clip-path: ' + style.clipPath);
      const v = m[1].trim().split(/\s+/).map(parseFloat);
      const left = v.length === 1 ? v[0] : v.length === 2 ? v[1] : v.length === 3 ? v[1] : v[3];
      if (Number.isNaN(left)) throw new Error('unreadable clip-path: ' + style.clipPath);
      return el.getBoundingClientRect().left + left - relRect(rel).left;
    }
    case 'center-offset-y':
    case 'center-offset-x': {
      // Where the part's center is, from the center of rel (0 when centered).
      const a = el.getBoundingClientRect();
      const b = relRect(rel);
      return metric === 'center-offset-y' ? a.top + a.height / 2 - (b.top + b.height / 2) : a.left + a.width / 2 - (b.left + b.width / 2);
    }
    case 'radius-top-right':
      return Math.min(px(style.borderTopRightRadius, box.width), Math.min(box.width, box.height) / 2);
    case 'radius-bottom-right':
      return Math.min(px(style.borderBottomRightRadius, box.width), Math.min(box.width, box.height) / 2);
    case 'radius-bottom-left':
      return Math.min(px(style.borderBottomLeftRadius, box.width), Math.min(box.width, box.height) / 2);
    case 'line-height':
      return parseFloat(style.lineHeight);
    case 'css-width':
      return parseFloat(style.width);
    case 'css-height':
      return parseFloat(style.height);
    case 'radius':
      // CSS clamps the radius to half the box, which is what is drawn.
      return Math.min(px(style.borderTopLeftRadius, box.width), Math.min(box.width, box.height) / 2);
    case 'clip-size':
      return clipSize(el, pseudo);
    case 'clip-radius':
      return px(/round ([\d.]+(px|%))/.exec(style.clipPath)?.[1] ?? '0px', box.width);
    case 'gap':
      return parseFloat(style.columnGap) || 0;
    case 'row-gap':
      return parseFloat(style.rowGap) || 0;
    case 'border-bottom':
      return parseFloat(style.borderBottomWidth);
    case 'border':
      return parseFloat(style.borderTopWidth);
    case 'font-size':
      return parseFloat(style.fontSize);
    case 'padding-left':
    case 'padding-right':
    case 'padding-top':
    case 'padding-bottom':
    case 'margin-left':
    case 'margin-right':
    case 'margin-top':
    case 'margin-bottom':
      return parseFloat(style.getPropertyValue(metric));
  }
  throw new Error('unknown metric ' + metric);
}

/**
 * Waits until the part's box and shape stop changing (8 still frames, since a
 * spring can clamp at 0 while it overshoots): some state changes
 * (a pressed shape) run as spring transitions that getAnimations() does not
 * list, so they can't be finished.
 */
async function settleStyle(chain: string) {
  const el = need(chain);
  const snapshot = () => {
    const s = getComputedStyle(el);
    const r = el.getBoundingClientRect();
    return [s.borderTopLeftRadius, s.width, s.height, s.clipPath, r.left, r.top].join('|');
  };
  let last = '';
  for (let stable = 0, frames = 0; stable < 8 && frames < 120; frames++) {
    await new Promise((resolve) => requestAnimationFrame(resolve));
    const now = snapshot();
    stable = now === last ? stable + 1 : 0;
    last = now;
  }
}

/** Checks a computed style property against any of the pipe-separated values. */
function expectCss(chain: string, prop: string, values: string, pseudo = '') {
  const actual = getComputedStyle(need(chain), pseudo).getPropertyValue(prop);
  expect(values.split('|')).withContext(chain + pseudo + ' ' + prop + ' is ' + actual).toContain(actual);
}

function expectDp(chain: string, metric: string, spec: Spec, pseudo = '') {
  const actual = measure(chain, metric, pseudo, spec.rel);
  if (spec.like !== undefined) spec = {...spec, eq: measure(spec.like, metric, pseudo)};
  const what = chain + pseudo + ' ' + metric + ' is ' + actual;
  if (spec.full) {
    const box = boxOf(need(chain), pseudo);
    expect(actual).withContext(what + ', spec: fully rounded').toBeGreaterThanOrEqual(Math.min(box.width, box.height) / 2 - TOLERANCE);
  }
  if (spec.eq !== undefined) expect(Math.abs(actual - spec.eq)).withContext(what + ', spec ' + spec.eq).toBeLessThanOrEqual(TOLERANCE);
  if (spec.min !== undefined) expect(actual).withContext(what + ', spec min ' + spec.min).toBeGreaterThanOrEqual(spec.min - TOLERANCE);
  if (spec.max !== undefined) expect(actual).withContext(what + ', spec max ' + spec.max).toBeLessThanOrEqual(spec.max + TOLERANCE);
}
`;

/**
 * Drops the top-level helper functions (with their doc comment) that nothing
 * else in the generated file calls, so the file has no unused locals.
 */
export function pruneHelpers(text) {
  const block = /^(?:\/\*\*(?:(?!\*\/)[\s\S])*\*\/\n)?(?:async )?function (\w+)\([\s\S]*?\n\}\n\n?/gm;
  for (;;) {
    let changed = false;
    text = text.replace(block, (all, name) => {
      const uses = text.match(new RegExp(`\\b${name}\\b`, 'g')).length;
      if (uses > 1) return all;
      changed = true;
      return '';
    });
    if (!changed) return text;
  }
}
