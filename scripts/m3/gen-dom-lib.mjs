let unitsCache;
/** Every spec unit, in document order. */
export async function loadUnits() {
  unitsCache ??= JSON.parse(await readFile('.m3-specs/spec-checks/units.json', 'utf8'));
  return Array.isArray(unitsCache) ? unitsCache : unitsCache.units;
}

/** Does the unit's text equal `cell`, or is `cell` its first merged cell? */
export function cellMatches(unit, cell) {
  return unit.text === cell || unit.text.startsWith(`${cell} |`) || unit.text.startsWith(`${cell}](`);
}

/**
 * Finds the units of one table row: `cells` are texts of consecutive table
 * cells (at most `WINDOW` units apart), searched from `cursor` on. Throws
 * when a cell can't be found, so a stale config fails loudly.
 *
 * @returns {{ids: string[], end: number}}
 */
export function resolveCells(units, cells, cursor, where) {
  const WINDOW = 4;
  for (let i = cursor; i < units.length; i++) {
    if (!cellMatches(units[i], cells[0])) continue;
    const ids = [units[i].id];
    let at = i;
    let ok = true;
    for (const cell of cells.slice(1)) {
      let found = -1;
      for (let j = at + 1; j <= at + WINDOW && j < units.length; j++) {
        if (cellMatches(units[j], cell)) {
          found = j;
          break;
        }
      }
      if (found < 0) {
        ok = false;
        break;
      }
      ids.push(units[found].id);
      at = found;
    }
    if (ok) return {ids, end: at + 1};
  }
  throw new Error(`${where}: no table cells ${JSON.stringify(cells)} after unit ${cursor}`);
}

