/** TypeScript helpers shared by the generated tests. */
export const TS_HELPERS = `let container: HTMLElement | undefined;

afterEach(() => container?.remove());

/** Renders the markup and waits for Lit updates and a frame. */
async function mount(markup: string) {
  container?.remove();
  container = document.createElement('div');
  document.body.appendChild(container);
  container.innerHTML = markup;
  await settle();
  return container;
}

async function settle(root: ParentNode = document.body) {
  for (const el of root.querySelectorAll('*')) {
    const update = (el as Partial<ReactiveElement>).updateComplete;
    if (update) await update;
    if (el.shadowRoot) await settle(el.shadowRoot);
  }
  if (root !== document.body) return;
  await new Promise((resolve) => requestAnimationFrame(resolve));
  // Finish transitions instead of waiting for them (animations may hold a
  // state, e.g. a pressed shape, and are left running).
  document.getAnimations().forEach((a) => a instanceof CSSTransition && a.finish());
}

/**
 * Finds an element by a chain of selectors: the first is queried in the
 * mounted markup, each \`>>\` goes into the previous element's shadow root
 * (a segment starting with \`light:\` queries its light DOM instead).
 * Returns null when any link of the chain is missing.
 */
function find(chain: string): HTMLElement | null {
  let el: ParentNode | null = container!;
  for (const raw of chain.split('>>')) {
    const segment = raw.trim();
    if (!segment) continue;
    if (!el) return null;
    if (segment.startsWith('light:')) {
      el = el.querySelector(segment.slice('light:'.length).trim());
    } else {
      const root: ParentNode | null = el === container ? el : (el as Element).shadowRoot;
      el = root?.querySelector(segment) ?? null;
    }
  }
  return el as HTMLElement | null;
}

function need(chain: string): HTMLElement {
  const el = find(chain);
  if (!el) throw new Error(\`no element for \${chain}\`);
  return el;
}
`;

/**
 * Writes (or with `check`, compares) one generated file; removes it when
 * there is nothing to write. Returns true when it is out of date.
 */
export async function emit(path, text, check) {
  const old = await readFile(path, 'utf8').then((s) => s.replace(/\r\n/g, '\n'), () => null);
  if (text === null) {
    if (old === null) return false;
    if (check) {
      console.log(`out of date: ${path} (should not exist)`);
      return true;
    }
    await rm(path);
    console.log(`removed ${path}`);
    return false;
  }
  if (old === text) return false;
  if (check) {
    console.log(`out of date: ${path}`);
    return true;
  }
  await writeFile(path, text);
  console.log(`wrote ${path}`);
  return false;
}

