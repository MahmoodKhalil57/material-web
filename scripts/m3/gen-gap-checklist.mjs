/**
 * Writes the "Spec gaps by section" block of scripts/m3/CHECKLIST.md: one open
 * item per spec section that still has units neither in code nor excluded,
 * citing the section with `spec-gap:` so `spec-checks.mjs` counts its open
 * units as tracked. IDs and counts only, no spec text.
 *
 *   node scripts/m3/gen-gap-checklist.mjs   # after node scripts/m3/spec-checks.mjs
 *
 * Reads `.m3-specs/spec-checks/units.json`. Rewrites only the lines between
 * the `spec-gaps:start` / `spec-gaps:end` markers; ticking an item by hand is
 * kept until its section has no open units left (then the line disappears).
 */

import {readFileSync, writeFileSync} from 'node:fs';

const CHECKLIST = 'scripts/m3/CHECKLIST.md';
const START = '<!-- spec-gaps:start -->';
const END = '<!-- spec-gaps:end -->';
/** Section depth below the page: page/tab/section. */
const DEPTH = 3;
const OPEN = new Set(['uncovered', 'label', 'tracked']);
const MODAL = /\b(must|should(n.t)?|never|always|don.t|do not|can.t|cannot|required?|avoid|only|ensure)\b/i;

const units = JSON.parse(readFileSync('.m3-specs/spec-checks/units.json', 'utf8'));
const sections = new Map();
for (const u of units) {
  if (!OPEN.has(u.status)) continue;
  const id = u.section.split('/').slice(0, DEPTH).join('/');
  if (!sections.has(id)) sections.set(id, {n: 0, normative: 0, page: u.page, ids: []});
  const s = sections.get(id);
  s.n++;
  s.ids.push(u.id);
  if (MODAL.test(u.text)) s.normative++;
}

const text = readFileSync(CHECKLIST, 'utf8');
const eol = text.includes('\r\n') ? '\r\n' : '\n';
const body = text.replace(/\r\n/g, '\n');
const done = new Set([...body.matchAll(/- \[x\] .*?spec-gap: ([^\s>]+)/g)].map((m) => m[1]));

const byPage = new Map();
for (const [id, s] of [...sections].sort(([a], [b]) => a.localeCompare(b))) {
  if (!byPage.has(s.page)) byPage.set(s.page, []);
  byPage.get(s.page).push([id, s]);
}
const total = [...sections.values()].reduce((n, s) => n + s.n, 0);
const lines = [
  START,
  `Generated by \`scripts/m3/gen-gap-checklist.mjs\` from \`spec-checks.mjs\`: ${sections.size} spec sections with ${total} units that are neither in code nor excluded. Each line tracks its section's open units (\`spec-gap:\`); build the feature, cite it in code with \`spec:\`, and the line goes away on the next run.`,
  '',
];
for (const [page, list] of byPage) {
  lines.push(`- **${page.replace(/\.md$/, '')}**`);
  for (const [id, s] of list) {
    const box = done.has(id) ? 'x' : ' ';
    // A page-level intro has no section below the page: cite its units.
    const tail = id.includes('/') ? id.split('/').slice(1).join(' › ') : 'page introduction';
    lines.push(`  - [${box}] ${tail} (${s.n} unit${s.n === 1 ? '' : 's'}${s.normative ? `, ${s.normative} must/should` : ''}) <!-- spec-gap: ${id.includes('/') ? id : s.ids.join(', ')} -->`);
  }
}
lines.push(END);

let out;
if (body.includes(START) && body.includes(END)) {
  out = body.slice(0, body.indexOf(START)) + lines.join('\n') + body.slice(body.indexOf(END) + END.length);
} else {
  out = body.trimEnd() + '\n\n## Spec gaps by section (generated)\n\n' + lines.join('\n') + '\n';
}
writeFileSync(CHECKLIST, eol === '\r\n' ? out.replace(/\n/g, '\r\n') : out);
console.log(`${CHECKLIST}: ${sections.size} sections, ${total} open units`);
