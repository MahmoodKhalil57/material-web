/**
 * Generates SVG path data for the Material 3 Expressive shapes.
 *
 * Shapes are built with the JS port of androidx.compose.material3.MaterialShapes
 * (scripts/m3/shapes/) and emitted normalized to a 0..1 unit box, as in
 * Compose. Also writes a preview page with every shape and a few morphs.
 *
 *   node scripts/m3/gen-shapes.mjs [--out styles/shape/material-shapes.ts]
 *                                  [--preview .m3-specs/shapes-preview.html]
 */

import {mkdir, writeFile} from 'node:fs/promises';
import {dirname} from 'node:path';
import {Morph} from './shapes/graphics-shapes.mjs';
import {
  MATERIAL_SHAPE_BUILDERS,
  MaterialShapes,
  cubicsToSvgPath,
  toCamelCase,
  toSvgPath,
} from './shapes/material-shapes.mjs';

const arg = (flag, fallback) =>
  process.argv.includes(flag) ? process.argv[process.argv.indexOf(flag) + 1] : fallback;

const OUT = arg('--out', 'styles/shape/material-shapes.ts');
const PREVIEW = arg('--preview', '.m3-specs/shapes-preview.html');
const DIGITS = 4;

const MORPHS = [
  ['Circle', 'Cookie9Sided'],
  ['Square', 'Sunny'],
  ['Pill', 'Heart'],
  ['Triangle', 'Clover4Leaf'],
  ['SoftBurst', 'Flower'],
];
const PROGRESS = [0, 0.25, 0.5, 0.75, 1];

const names = Object.keys(MATERIAL_SHAPE_BUILDERS);
const paths = names.map((name) => [name, toSvgPath(MaterialShapes[name], DIGITS)]);

// --- TypeScript data module ------------------------------------------------

const ts = `/**
 * @license
 * Copyright 2026 Google LLC
 * SPDX-License-Identifier: Apache-2.0
 */

// AUTOGENERATED. DO NOT MODIFY. Run node scripts/m3/gen-shapes.mjs
//
// Shapes ported from androidx.compose.material3.MaterialShapes and
// androidx.graphics.shapes (Apache-2.0).
//
// SVG path data for each Material 3 Expressive shape, normalized to a 0..1
// unit box (as MaterialShapes does with RoundedPolygon.normalized()). Scale
// with a viewBox="0 0 1 1" or clip-path: path() after scaling.

/** Material 3 Expressive shapes as SVG path data in a 0..1 unit box. */
export const MATERIAL_SHAPES = {
${paths.map(([name, d]) => `  ${toCamelCase(name)}: '${d}',`).join('\n')}
} as const;

/** Name of a Material 3 Expressive shape. */
export type MaterialShapeName = keyof typeof MATERIAL_SHAPES;
`;

// --- Preview page ----------------------------------------------------------

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
const svg = (d, title) =>
  `<svg viewBox="-0.05 -0.05 1.1 1.1" role="img" aria-label="${esc(title)}">` +
  `<rect class="box" x="0" y="0" width="1" height="1"/><path d="${d}"/></svg>`;

const shapeCells = paths
  .map(
    ([name, d]) =>
      `<figure>${svg(d, name)}<figcaption>${name}<br><code>${toCamelCase(name)}</code></figcaption></figure>`,
  )
  .join('\n');

const morphRows = MORPHS.map(([a, b]) => {
  const morph = new Morph(MaterialShapes[a], MaterialShapes[b]);
  const cells = PROGRESS.map((p) => {
    const d = cubicsToSvgPath(morph.asCubics(p), DIGITS);
    return `<figure>${svg(d, `${a} to ${b} at ${p}`)}<figcaption>${p}</figcaption></figure>`;
  }).join('\n');
  return `<h3>${a} &rarr; ${b}</h3>\n<div class="strip">\n${cells}\n</div>`;
}).join('\n');

const html = `<!doctype html>
<!--
  @license
  Copyright 2026 Google LLC
  SPDX-License-Identifier: Apache-2.0

  AUTOGENERATED. DO NOT MODIFY. Run node scripts/m3/gen-shapes.mjs
  Shapes ported from androidx.compose.material3.MaterialShapes and
  androidx.graphics.shapes (Apache-2.0).
-->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Material Shapes Preview</title>
<style>
  :root { color-scheme: light dark; --bg: #fef7ff; --fg: #1d1b20; --shape: #6750a4; --box: #cac4d0; --card: #f3edf7; }
  @media (prefers-color-scheme: dark) { :root { --bg: #141218; --fg: #e6e0e9; --shape: #d0bcff; --box: #49454f; --card: #211f26; } }
  body { margin: 0; padding: 24px 16px; background: var(--bg); color: var(--fg); font: 14px/1.4 system-ui, sans-serif; }
  h1 { font-size: 22px; margin: 0 0 4px; }
  p { margin: 0 0 20px; opacity: .75; }
  h2 { font-size: 18px; margin: 32px 0 12px; }
  h3 { font-size: 14px; margin: 20px 0 8px; font-weight: 600; }
  .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(120px, 1fr)); gap: 12px; }
  .strip { display: grid; grid-template-columns: repeat(${PROGRESS.length}, minmax(0, 120px)); gap: 12px; }
  figure { margin: 0; padding: 10px; background: var(--card); border-radius: 12px; text-align: center; }
  svg { width: 100%; aspect-ratio: 1; display: block; }
  svg path { fill: var(--shape); }
  svg .box { fill: none; stroke: var(--box); stroke-width: .006; stroke-dasharray: .02 .02; }
  figcaption { margin-top: 6px; font-size: 12px; }
  code { font-size: 11px; opacity: .7; }
</style>
</head>
<body>
<h1>Material 3 Expressive shapes</h1>
<p>${paths.length} shapes from MaterialShapes, normalized to the 0..1 box (dashed). Generated by scripts/m3/gen-shapes.mjs.</p>
<h2>Shapes</h2>
<div class="grid">
${shapeCells}
</div>
<h2>Morphs</h2>
<p>Morph.asCubics(progress) at ${PROGRESS.join(', ')}.</p>
${morphRows}
</body>
</html>
`;

for (const [file, content] of [
  [OUT, ts],
  [PREVIEW, html],
]) {
  await mkdir(dirname(file), {recursive: true});
  await writeFile(file, content.replace(/\r\n/g, '\n'));
  console.log(`wrote ${file}`);
}
console.log(`${paths.length} shapes, ${MORPHS.length} morph strips`);
