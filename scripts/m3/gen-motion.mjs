/**
 * Generates CSS spring easings from the M3 motion tokens.
 *
 * CSS has no spring timing function, so each `md.sys.motion.spring.*` token
 * (damping ratio + stiffness, unit mass, as in Jetpack Compose `spring()`) is
 * solved in closed form and emitted as a `linear()` easing plus the duration
 * after which the spring stays within SETTLE of its target.
 *
 * Reduced motion (spec, styles/motion/transitions "Follows accessibility
 * settings": use subtle fades instead of sliding or scaling, disable
 * decorative effects like parallax or shape morphing): with
 * `prefers-reduced-motion: reduce`, or inside `.md-motion-reduced`, the
 * spatial springs (position, size, shape) finish instantly while the effects
 * springs (opacity, color) keep animating, so every transition built on the
 * spring tokens degrades to a fade.
 *
 *   node scripts/m3/gen-motion.mjs [--out labs/gb/styles/motion/md-motion-tokens-spring.scss]
 */

import {writeFile} from 'node:fs/promises';
import {SpecDb, WEB_CONTEXT} from './spec-db.mjs';
import {settleTime, springEasing} from './spring.mjs';

const OUT = process.argv.includes('--out')
  ? process.argv[process.argv.indexOf('--out') + 1]
  : 'labs/gb/styles/motion/md-motion-tokens-spring.scss';

/** Max |x - 1| after the duration ends. */
const SETTLE = 0.002;
/** Max error of the piecewise-linear approximation. */
const TOLERANCE = 0.002;

const SPRINGS = ['fast-spatial', 'default-spatial', 'slow-spatial', 'fast-effects', 'default-effects', 'slow-effects'];
const SCHEMES = {expressive: {'motion.scheme': 'expressive'}, standard: {'motion.scheme': 'standard'}};

const db = await SpecDb.load();

function springParams(name, ctx) {
  const get = (part) => {
    const r = db.resolve(`md.sys.motion.spring.${name.replace('-', '.')}.${part}`, ctx);
    const v = r?.value?.numeric ?? r?.resolved?.numeric;
    if (v === undefined) throw new Error(`Missing md.sys.motion.spring.${name}.${part}`);
    return v;
  };
  return {damping: get('damping'), stiffness: get('stiffness')};
}

/** Spatial springs collapse to an instant change with reduced motion. */
function reducedDeclarations(indent) {
  return SPRINGS.filter((name) => name.endsWith('-spatial'))
    .map(
      (name) =>
        `${indent}--md-sys-motion-spring-${name}: linear;\n` +
        `${indent}--md-sys-motion-spring-${name}-duration: 0ms;\n`,
    )
    .join('');
}

function declarations(scheme, indent) {
  const ctx = {...WEB_CONTEXT, ...SCHEMES[scheme]};
  return SPRINGS.map((name) => {
    const {damping, stiffness} = springParams(name, ctx);
    const duration = settleTime(damping, stiffness, SETTLE);
    return (
      `${indent}// md.sys.motion.spring.${name.replace('-', '.')}: damping ${damping}, stiffness ${stiffness}\n` +
      `${indent}--md-sys-motion-spring-${name}: ${springEasing(damping, stiffness, duration, TOLERANCE)};\n` +
      `${indent}--md-sys-motion-spring-${name}-duration: ${Math.round(duration * 1000)}ms;\n`
    );
  }).join('');
}

const scss = `//
// Copyright 2026 Google LLC
// SPDX-License-Identifier: Apache-2.0
//
// AUTOGENERATED. DO NOT MODIFY.
// To modify this file, run: node scripts/m3/gen-motion.mjs
// Source: m3.material.io ${db.version} (md.sys.motion.spring.*)
//
// Springs as CSS easings: each spring is solved in closed form and sampled
// into a \`linear()\` easing, with a duration after which it stays within
// ${SETTLE} of its target. Use as:
//   transition: width var(--md-sys-motion-spring-fast-spatial-duration)
//     var(--md-sys-motion-spring-fast-spatial);

@layer md.sys.motion {
  // M3 Expressive motion scheme (default).
  :root {
${declarations('expressive', '    ')}  }

  // Standard motion scheme.
  :where(.md-motion-standard) {
${declarations('standard', '    ')}  }

  // Reduced motion (spec: transitions follow the platform setting and use
  // fades instead of sliding, scaling or shape morphing). Spatial springs end
  // instantly; effects springs (fades, color) are unchanged.
  @media (prefers-reduced-motion: reduce) {
    :root,
    :where(.md-motion-standard) {
${reducedDeclarations('      ')}    }
  }

  // Opts a subtree into reduced motion regardless of the platform setting.
  :where(.md-motion-reduced) {
${reducedDeclarations('    ')}  }
}
`;
await writeFile(OUT, scss);
console.log(`Wrote ${OUT} (${SPRINGS.length} springs x ${Object.keys(SCHEMES).length} schemes).`);
