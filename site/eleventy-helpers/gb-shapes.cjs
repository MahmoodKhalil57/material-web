/**
 * The M3 Expressive shape library (styles/shape/material-shapes.ts:
 * paths in a 0..1 box) on the /3.0/ pages: the section index pages
 * (gb-sections.11ty.cjs), the compatibility rows (gb-compat.cjs) and the
 * `gbshape` shortcode (shortcodes/gb.cjs) write an inline SVG marked with
 * its shape and morph, which the pages draw with md-gb-shape (shapeProps:
 * gb-content-spec.cjs, and the all-pages document).
 *
 * A shape can morph into another (m3.material.io/styles/shape/shape-morph):
 * the pairs below get matched start and end paths, generated by
 * scripts/gb-shape-morphs.mjs with the Compose `Morph` port into
 * md-gb-shape's morphs: in a loop, or while the card or tile around the
 * shape is hovered or focused.
 */

const {readFileSync} = require('node:fs');
const {join} = require('node:path');

const ROOT = join(__dirname, '..', '..');

let shapePaths;
/** The path of a Material shape, in a 0..1 box. */
function shapePath(name) {
  if (!shapePaths) {
    const src = readFileSync(join(ROOT, 'material-design-expressive', 'styles', 'shape', 'material-shapes.ts'), 'utf8');
    shapePaths = Object.fromEntries([...src.matchAll(/^\s+(\w+): '([^']+)',?$/gm)].map((m) => [m[1], m[2]]));
  }
  if (!shapePaths[name]) throw new Error(`gb-shapes: no shape "${name}"`);
  return shapePaths[name];
}

/**
 * The morphs the pages use, [from, to]: the section heroes' loops, the
 * section cards' (each card's shape into the next one's), and the home
 * page's (hero loops, the carousel tiles, the cards' shapes).
 */
const MORPHS = [
  // Section heroes (loops).
  ['cookie9Sided', 'flower'],
  ['clover4Leaf', 'clover8Leaf'],
  ['sunny', 'softBurst'],
  ['pill', 'oval'],
  // Section cards: the illustration shapes, each into the next.
  ['clover4Leaf', 'sunny'],
  ['sunny', 'flower'],
  ['flower', 'puffy'],
  ['puffy', 'cookie6Sided'],
  ['cookie6Sided', 'softBurst'],
  ['softBurst', 'pill'],
  ['pill', 'pentagon'],
  ['pentagon', 'cookie12Sided'],
  ['cookie12Sided', 'gem'],
  ['gem', 'burst'],
  ['burst', 'cookie9Sided'],
  ['cookie9Sided', 'clover4Leaf'],
  // Home: hero loops, carousel tiles and card shapes.
  ['cookie12Sided', 'cookie9Sided'],
  ['clover4Leaf', 'puffy'],
  ['sunny', 'verySunny'],
  ['softBurst', 'burst'],
  ['clover8Leaf', 'clover4Leaf'],
  ['burst', 'softBurst'],
  ['flower', 'cookie9Sided'],
  ['puffy', 'puffyDiamond'],
  ['gem', 'pentagon'],
  ['cookie6Sided', 'cookie9Sided'],
  ['puffyDiamond', 'puffy'],
  ['cookie4Sided', 'cookie6Sided'],
  ['softBoom', 'boom'],
];
const morphKey = (from, to) => `${from}:${to}`;
const MORPH_KEYS = new Set(MORPHS.map(([a, b]) => morphKey(a, b)));

/**
 * An inline SVG of a Material shape (filled with currentColor), decorative.
 * With `to`, it morphs into that shape: in a loop with `loop` (`delay` 0-3
 * staggers it, a quarter of the loop each), else when the card or tile
 * around it is hovered or focused.
 */
function shapeSvg(name, cls = '', {to = '', loop = false, delay = 0} = {}) {
  let morph = '';
  if (to) {
    if (!MORPH_KEYS.has(morphKey(name, to))) {
      throw new Error(`gb-shapes: no morph "${name}" -> "${to}" (add it to MORPHS and run scripts/gb-shape-morphs.mjs)`);
    }
    morph = ` data-morph="${morphKey(name, to)}"`;
    if (loop) morph += ' data-morph-mode="loop"';
    if (loop && delay) morph += ` data-delay="${Number(delay)}"`;
  }
  // data-shape names it for the spec shell, which draws it with md-gb-shape
  // (gb-content-spec.cjs).
  return `<svg class="gb-shape ${cls}" viewBox="0 0 1 1" aria-hidden="true" focusable="false" data-shape="${name}"${morph}><path d="${shapePath(name)}"/></svg>`;
}

/** A compatibility row's status (gb-compat.cjs) -> its shape's color role. */
const STATE_COLORS = {
  ok: 'secondary-container',
  warn: 'error-container',
  none: 'surface-container-highest',
  info: 'surface-container-highest',
};

/**
 * The md-gb-shape props of a shape's SVG (shapeSvg): `attrs` are the SVG's
 * attributes; from its ancestors, `tone` (data-tone of its tile or card),
 * `state` (data-state of its compatibility row) and `classes` (their class
 * lists, which size it as the old shell's styles did).
 */
function shapeProps(attrs, {tone = '', state = '', classes = ''} = {}) {
  const [, to = ''] = (attrs['data-morph'] ?? '').split(':');
  let size = 48;
  if (/\bgb-home-blob\b|\bgb-hero-shape\b/.test(classes)) size = 96;
  else if (/\bgb-home-tile\b|\bgb-card\b|\bgb-home-card\b/.test(classes)) size = 72;
  else if (/\bgb-compat-logo\b/.test(classes)) size = 40;
  const props = {
    shape: attrs['data-shape'],
    size,
    color: tone ? `${tone}-container` : (STATE_COLORS[state] ?? 'current'),
  };
  if (to) {
    props.to = to;
    // Heroes loop; a card's or tile's shape morphs while it's hovered or
    // focused.
    if (attrs['data-morph-mode'] === 'loop') props.loop = true;
    else props.morphOnHover = true;
    if (attrs['data-delay']) props.delay = Number(attrs['data-delay']);
  }
  return props;
}

/** shapeProps as md-gb-shape's attributes. */
function shapeAttributes(props) {
  return [
    `shape="${props.shape}"`,
    `size="${props.size}"`,
    `color="${props.color}"`,
    props.to ? `to="${props.to}"` : '',
    props.loop ? 'loop' : '',
    props.morphOnHover ? 'morph-on-hover' : '',
    props.delay ? `delay="${props.delay}"` : '',
  ]
    .filter(Boolean)
    .join(' ');
}

module.exports = {MORPHS, morphKey, shapePath, shapeSvg, shapeProps, shapeAttributes};
