const markdownIt = require('markdown-it');
const docsShortcodes = require('./eleventy/shortcodes.cjs');
const {sitePlugin} = require('./eleventy/site.cjs');
const permalinks = require('./eleventy/permalinks.cjs');

module.exports = function (eleventyConfig) {
  eleventyConfig
    // The client bundle (esbuild.config.mjs writes lib/spec/).
    .addPassthroughCopy({'lib/': 'js/'})
    // The /3.0/ service worker is served from its scope (client/sw.ts).
    .addPassthroughCopy({'lib/spec/sw.js': '3.0/sw.js'})
    .addPassthroughCopy('content/fonts')
    .addPassthroughCopy('content/images')
    // The docs' images (docs/images, copied with the docs by scripts/dev.mjs).
    .addPassthroughCopy({'content/3.0/images': '3.0/images'});

  // The /3.0/ Open Graph images and manifest icons, generated by
  // site/scripts/assets.mjs (site/scripts/dev.mjs buildSite).
  eleventyConfig
    .addPassthroughCopy({'_generated/og': '3.0/og'})
    .addPassthroughCopy({'_generated/icons': '3.0/icons'})
    // The API manifest (Custom Elements Manifest) and the agent skill files.
    .addPassthroughCopy({'_generated/custom-elements.json': '3.0/custom-elements.json'})
    .addPassthroughCopy({'_generated/skill': '3.0/skill'});

  // Add this for 11ty's --watch flag
  eleventyConfig.addWatchTarget('./lib/**/*.js');

  docsShortcodes(eleventyConfig);
  // The spec shell (layout spec.html).
  require('./eleventy/render.cjs')(eleventyConfig);
  require('./eleventy/shadcn-shortcodes.cjs')(eleventyConfig);
  // /3.0/ site metadata: allPages collection, pagehead shortcode.
  sitePlugin(eleventyConfig);

  // Markdown with HTML (the demos), and heading ids with permalinks.
  const md = markdownIt({html: true, breaks: false, linkify: true});
  permalinks(md);
  eleventyConfig.setLibrary('md', md);

  return {
    htmlTemplateEngine: 'njk',
    markdownTemplateEngine: 'njk',
    dir: {input: 'content', output: '_dev'},
  };
};
